/**
 * Regenerate `bench/jev-recording.json` — the recorded TypeSafe decisions that let
 * `bf bench route` and `bf demo` run offline with no key.
 *
 *   node bench/make-recording.mjs
 *
 * This is a RECORDING STAND-IN, not a measurement. It is derived from the labeled set with a
 * fixed, legible rule so the bench arithmetic is reproducible without a key:
 *
 *   - Jev agrees with the expert lane label most of the time.
 *   - Where the label is `lead_keeps`/`unclear`, Jev proposes the cheapest passing lane at low
 *     confidence, which is what makes the escalation band real rather than decorative.
 *   - Every 11th task it under-routes by one tier and every 17th it proposes `codex_handoff`,
 *     so the under-routing guardrail and the agreement metric have something to catch.
 *   - Sensitivity and repo-context probabilities follow the labels with noise.
 *
 * Replace it with real numbers by running the API:
 *   TYPESAFE_API_KEY=... bf bench route --live --record bench/jev-recording.json
 */
import fs from "node:fs";
import path from "node:path";

const HERE = path.dirname(new URL(import.meta.url).pathname);
const set = fs
  .readFileSync(path.join(HERE, "route-set.jsonl"), "utf8")
  .split("\n")
  .filter((l) => l.trim())
  .map((l) => JSON.parse(l));

const TIER = ["local", "fast", "strong", "thinker"];
const CONFIDENCE = [0.92, 0.88, 0.84, 0.95, 0.79, 0.86, 0.9, 0.83];

const decisions = {};
set.forEach((t, i) => {
  const escalated = t.lead_lane === "lead_keeps" || t.lead_lane === "unclear";
  let lane;
  let confidence;
  if (escalated) {
    lane = t.cheapest_passing_lane;
    confidence = 0.42;
  } else if (i % 17 === 3) {
    lane = "codex_handoff";
    confidence = CONFIDENCE[i % CONFIDENCE.length];
  } else if (i % 11 === 5) {
    // one tier cheaper than the label: a deliberate under-route the guardrail should catch
    const idx = TIER.indexOf(t.lead_lane);
    lane = idx > 0 ? TIER[idx - 1] : t.lead_lane;
    confidence = 0.74;
  } else {
    lane = t.lead_lane;
    confidence = CONFIDENCE[i % CONFIDENCE.length];
  }
  const entry = {
    lane,
    confidence,
    difficulty: t.difficulty,
    sensitive: t.sensitive ? 0.9 : 0.06 + ((i % 5) * 0.01),
    context: t.needs_repo_context ? 0.9 : 0.1 + ((i % 4) * 0.05),
  };
  if (escalated) {
    const rest = Number(((1 - confidence) / 6).toFixed(4));
    entry.probs = Object.fromEntries(["local", "fast", "strong", "thinker", "codex_handoff", "lead_keeps", "unclear"].map((l) => [l, l === lane ? confidence : rest]));
  }
  decisions[t.id] = entry;
});

const out = {
  note: "Recorded stand-in for TypeSafe System One decisions, generated by bench/make-recording.mjs from the labeled lanes with a fixed rule. It exists so `bf bench route` and `bf demo` are reproducible with no key; it is NOT a measurement of Jev. Replace it with real numbers via: TYPESAFE_API_KEY=... bf bench route --live --record bench/jev-recording.json",
  answered_by: "recorded",
  generated_by: "bench/make-recording.mjs",
  tasks: set.length,
  decisions,
};

fs.writeFileSync(path.join(HERE, "jev-recording.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`wrote jev-recording.json (${set.length} decisions)`);
